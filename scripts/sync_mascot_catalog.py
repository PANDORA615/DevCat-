"""Generate typed-client input from original v5 and additional appearance manifests."""
import argparse
from pathlib import Path
root = Path(__file__).resolve().parents[1]
assets = root / 'apps/devcat_flutter/assets/mascot/manifests'
output = root / 'apps/devcat_flutter/lib/core/mascot_data.dart'
generated = '// Generated by scripts/sync_mascot_catalog.py. Do not edit.\n' + '\n'.join(
    f"const {variable} = r'''{(assets / filename).read_text().strip()}''';\n"
    for variable, filename in [('mascotAnimationJson', 'animation_contract.json'),
                               ('mascotAppearanceJson', 'appearance_catalog.json'),
                               ('mascotAppearanceAnimationsJson', 'appearance_animations.json')])
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if output.read_text() != generated:
        parser.error('mascot_data.dart is stale; run scripts/sync_mascot_catalog.py')
else:
    output.write_text(generated)
