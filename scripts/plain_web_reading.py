class Markup(HTMLParser):
    def __init__(self): super().__init__(); self.tags=[]
    def handle_starttag(self, tag, attrs): self.tags.append((tag, attrs))


def focused(lang, slug):
    unit = next(x for x in (HTML if lang == 'html' else CSS) if x[0] == slug)
    code, result, exercise = unit[3:]
    lines=[]
    if lang == 'html':
        p=Markup();p.feed(code)
        for tag, attrs in p.tags:
            lines.append('<'+tag+'> — '+TAGS[tag]+'.')
            for name,value in attrs:
                descriptions={
                    'class':'имя группы для оформления; точку перед ним пишут в CSS-селекторе, а не в этом значении',
                    'id':'уникальное имя элемента в пределах документа',
                    'href':'адрес перехода, отсчитываемый по правилам URL',
                    'src':'адрес настоящего ресурса, который должен существовать и быть доступен',
                    'alt':'текстовое замещение изображения по его назначению',
                    'for':'идентификатор поля, с которым связана подпись',
                    'name':'имя поля или метаданных в зависимости от элемента',
                    'type':'вид поля или поведения кнопки по правилам конкретного элемента',
                    'value':'значение данных варианта или поля, отличающееся от видимой подписи',
                    'required':'булево требование; само наличие атрибута включает правило',
                    'controls':'булев запрос встроенного управления воспроизведением',
                    'scope':'область действия табличного заголовка, например строка или столбец',
                }
                if name in descriptions:lines.append(name+('="'+value+'"' if value is not None else '')+' — '+descriptions[name]+'.')
        lines.append('Парные теги закрываются в допустимом порядке: сначала внутренний, потом внешний. Значение атрибута относится к своему открывающему тегу. Текст между тегами является содержимым, а не названием свойства.')
    else:
        for name,value in re.findall(r'(?:^|[;{])\s*([\w-]+)\s*:\s*([^;{}]+)(?=[;}])',code):
            assert name in PROPS,(slug,name)
            lines.append(name+': '+value.strip()+' — '+PROPS[name]+'.')
        lines.append('Селектор перед фигурной скобкой определяет, к чему относятся объявления. Двоеточие разделяет имя свойства и значение, точка с запятой — соседние объявления. Внутри @media сначала проверяется условие, а затем применяются соответствующие обычные правила.')
    lines += ['Наблюдаемый смысл этого примера: '+result,
              'Проверь по одному действию. 1. Сохрани исходный рабочий набор. 2. Найди именно приведённый фрагмент. 3. Выполни изменение ниже. 4. Сохрани и обнови браузер. 5. Сравни конкретный результат, а не только общее впечатление от страницы.',
              'Изменение для самостоятельного опыта: '+exercise]
    if slug == 'media' and lang == 'html':
        lines.append('Появление плеера ещё не подтверждает доступность аудиофайла. В примере отдельно проверь источник; при отсутствии ресурса остаётся текстовая альтернатива. Для настоящего звука нужен поддерживаемый доступный файл. Наличие controls не создаёт саму запись лекции.')
    return code,'\n\n'.join(lines),exercise
